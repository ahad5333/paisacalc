import type { Metadata } from "next";
import { SavingsGoalCalculatorLoader } from "./SavingsGoalCalculatorLoader";
import { SavingsGoalContent, FAQS } from "./SavingsGoalContent";
import { SITE_URL } from "@/lib/site-config";

const PAGE_URL = `${SITE_URL}/savings-goal/`;
const TITLE = "Savings Goal Calculator | PaisaCalc";
const DESCRIPTION =
  "Find out how much to save every month to reach a target amount by a chosen date, worked out step by step.";

export const metadata: Metadata = {
  title: TITLE,
  description: DESCRIPTION,
  alternates: { canonical: PAGE_URL },
  openGraph: { title: TITLE, description: DESCRIPTION, url: PAGE_URL, type: "website" },
};

const webApplicationSchema = {
  "@context": "https://schema.org",
  "@type": "WebApplication",
  name: "Savings Goal Calculator",
  url: PAGE_URL,
  applicationCategory: "FinanceApplication",
  operatingSystem: "Any (web browser)",
  offers: { "@type": "Offer", price: "0", priceCurrency: "INR" },
  description: DESCRIPTION,
};

const faqSchema = {
  "@context": "https://schema.org",
  "@type": "FAQPage",
  mainEntity: FAQS.map((item) => ({
    "@type": "Question",
    name: item.q,
    acceptedAnswer: { "@type": "Answer", text: item.a },
  })),
};

const breadcrumbSchema = {
  "@context": "https://schema.org",
  "@type": "BreadcrumbList",
  itemListElement: [
    { "@type": "ListItem", position: 1, name: "Home", item: `${SITE_URL}/` },
    { "@type": "ListItem", position: 2, name: "Savings Goal Calculator", item: PAGE_URL },
  ],
};

export default function SavingsGoalPage() {
  return (
    <>
      <script type="application/ld+json" dangerouslySetInnerHTML={{ __html: JSON.stringify(webApplicationSchema) }} />
      <script type="application/ld+json" dangerouslySetInnerHTML={{ __html: JSON.stringify(faqSchema) }} />
      <script type="application/ld+json" dangerouslySetInnerHTML={{ __html: JSON.stringify(breadcrumbSchema) }} />
      <SavingsGoalCalculatorLoader content={<SavingsGoalContent />} />
    </>
  );
}
