import type { Metadata } from "next";
import { MutualFundCalculatorLoader } from "./MutualFundCalculatorLoader";
import { MutualFundContent, FAQS } from "./MutualFundContent";
import { SITE_URL } from "@/lib/site-config";

const PAGE_URL = `${SITE_URL}/mutual-fund-calculator/`;
const TITLE = "Mutual Fund Calculator | PaisaCalc";
const DESCRIPTION =
  "What a lumpsum mutual fund investment grows to, and exactly how much the expense ratio costs you over the years.";

export const metadata: Metadata = {
  title: TITLE,
  description: DESCRIPTION,
  alternates: { canonical: PAGE_URL },
  openGraph: { title: TITLE, description: DESCRIPTION, url: PAGE_URL, type: "website" },
};

const webApplicationSchema = {
  "@context": "https://schema.org",
  "@type": "WebApplication",
  name: "Mutual Fund Calculator",
  url: PAGE_URL,
  applicationCategory: "FinanceApplication",
  operatingSystem: "Any (web browser)",
  offers: { "@type": "Offer", price: "0", priceCurrency: "INR" },
  description: DESCRIPTION,
};

const faqSchema = {
  "@context": "https://schema.org",
  "@type": "FAQPage",
  mainEntity: FAQS.map((item) => ({
    "@type": "Question",
    name: item.q,
    acceptedAnswer: { "@type": "Answer", text: item.a },
  })),
};

const breadcrumbSchema = {
  "@context": "https://schema.org",
  "@type": "BreadcrumbList",
  itemListElement: [
    { "@type": "ListItem", position: 1, name: "Home", item: `${SITE_URL}/` },
    { "@type": "ListItem", position: 2, name: "Mutual Fund Calculator", item: PAGE_URL },
  ],
};

export default function MutualFundPage() {
  return (
    <>
      <script type="application/ld+json" dangerouslySetInnerHTML={{ __html: JSON.stringify(webApplicationSchema) }} />
      <script type="application/ld+json" dangerouslySetInnerHTML={{ __html: JSON.stringify(faqSchema) }} />
      <script type="application/ld+json" dangerouslySetInnerHTML={{ __html: JSON.stringify(breadcrumbSchema) }} />
      <MutualFundCalculatorLoader content={<MutualFundContent />} />
    </>
  );
}
