import type { Metadata } from "next";
import { SampleSizeCalculatorLoader } from "./SampleSizeCalculatorLoader";
import { SampleSizeContent, FAQS } from "./SampleSizeContent";
import { SITE_URL } from "@/lib/site-config";

const PAGE_URL = `${SITE_URL}/sample-size-calculator/`;
const TITLE = "Sample Size Calculator | PaisaCalc";
const DESCRIPTION = "Minimum survey sample size for a confidence level and margin of error.";

