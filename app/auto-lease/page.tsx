import type { Metadata } from "next";
import { AutoLeaseCalculatorLoader } from "./AutoLeaseCalculatorLoader";
import { AutoLeaseContent, FAQS } from "./AutoLeaseContent";
import { SITE_URL } from "@/lib/site-config";

const PAGE_URL = `${SITE_URL}/auto-lease/`;
const TITLE = "Auto Lease Calculator | PaisaCalc";
const DESCRIPTION =
  "Monthly lease payment for a car — the depreciation charge plus the finance charge, the two pieces every lease payment is built from.";

export const metadata: Metadata = {
  title: TITLE,
  description: DESCRIPTION,
  alternates: { canonical: PAGE_URL },
  openGraph: { title: TITLE, description: DESCRIPTION, url: PAGE_URL, type: "website" },
};

const webApplicationSchema = {
  "@context": "https://schema.org",
  "@type": "WebApplication",
  name: "Auto Lease Calculator",
  url: PAGE_URL,
  applicationCategory: "FinanceApplication",
  operatingSystem: "Any (web browser)",
  offers: { "@type": "Offer", price: "0", priceCurrency: "INR" },
  description: DESCRIPTION,
};

const faqSchema = {
  "@context": "https://schema.org",
  "@type": "FAQPage",
  mainEntity: FAQS.map((item) => ({
    "@type": "Question",
    name: item.q,
    acceptedAnswer: { "@type": "Answer", text: item.a },
  })),
};

const breadcrumbSchema = {
  "@context": "https://schema.org",
  "@type": "BreadcrumbList",
  itemListElement: [
    { "@type": "ListItem", position: 1, name: "Home", item: `${SITE_URL}/` },
    { "@type": "ListItem", position: 2, name: "Auto Lease Calculator", item: PAGE_URL },
  ],
};

export default function AutoLeasePage() {
  return (
    <>
      <script type="application/ld+json" dangerouslySetInnerHTML={{ __html: JSON.stringify(webApplicationSchema) }} />
      <script type="application/ld+json" dangerouslySetInnerHTML={{ __html: JSON.stringify(faqSchema) }} />
      <script type="application/ld+json" dangerouslySetInnerHTML={{ __html: JSON.stringify(breadcrumbSchema) }} />
      <AutoLeaseCalculatorLoader content={<AutoLeaseContent />} />
    </>
  );
}
